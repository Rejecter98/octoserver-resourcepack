def deco(n, face, px, w, h, m):
    if m == "iron":  # 따개비
        for y in range(h):
            for x in range(w):
                if (x * 5 + y * 3) % 13 == 0:
                    px[y][x] = C(236, 230, 214)
    if m == "chain" and face not in ("up", "down"):
        for x in range(w):
            if x % 3 == 1:
                for y in range(h):
                    setpx(px, x, y, C(80, 86, 98))
    if n == "chest" and face == "north":  # 가슴 닻 문양
        cx, col = w // 2, C(120, 88, 40)
        for y in range(1, h - 1):
            setpx(px, cx, y, col)
        for x in range(cx - 2, cx + 3):
            setpx(px, x, h - 2, col)
        setpx(px, cx - 1, 1, col); setpx(px, cx + 1, 1, col)
    if n == "glass" and face == "north":  # 빛 반사
        setpx(px, 1, 1, C(255, 255, 255)); setpx(px, 2, 1, C(255, 255, 255)); setpx(px, 1, 2, C(255, 255, 255))
    return px


